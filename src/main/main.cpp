// The window/taskbar icon, from icons/app.png (embedded as icon_bytes, decoded
// with the stb_image that RT64 already links in). The .exe's own icon comes
// from icons/app.rc on Windows.
static void set_window_icon(SDL_Window* window) {
#if defined(SNP_HAS_APP_ICON)
    int width, height, channels;
    stbi_uc* pixels = stbi_load_from_memory(reinterpret_cast<const stbi_uc*>(icon_bytes), (int)icon_bytes_size, &width, &height, &channels, 4);
    if (pixels == nullptr) {
        return;
    }
    SDL_Surface* surface = SDL_CreateRGBSurfaceWithFormatFrom(pixels, width, height, 32, width * 4, SDL_PIXELFORMAT_RGBA32);
    if (surface != nullptr) {
        SDL_SetWindowIcon(window, surface);
        SDL_FreeSurface(surface);
    }
    stbi_image_free(pixels);
#else
    (void)window;
#endif
}

static ultramodern::renderer::WindowHandle create_window(ultramodern::gfx_callbacks_t::gfx_data_t) {

    uint32_t flags = SDL_WINDOW_RESIZABLE;
#if defined(__APPLE__)
    flags |= SDL_WINDOW_METAL;
#elif defined(RT64_SDL_WINDOW_VULKAN) || defined(__ANDROID__)
    // Linux only (CMakeLists.txt); Windows uses D3D12 through the HWND below.
    // On Android the flag matters too: without a graphics flag SDL defaults to
    // OpenGL there and connects an EGL surface to the window, after which
    // Vulkan can't create its own surface on it.
    flags |= SDL_WINDOW_VULKAN;
#endif
#if defined(__ANDROID__)
    // Always fullscreen on Android: SDL then hides the system bars (immersive
    // mode), so the game gets the whole screen. The window mode setting goes
    // through RT64, which has no Android path (lib-patches/RecompFrontend/0016).
    flags |= SDL_WINDOW_FULLSCREEN_DESKTOP;
#endif

    window = SDL_CreateWindow(program_name.c_str(), SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED, 1280, 720, flags);
    if (window == nullptr) {
        exit_error("Failed to create window: %s", SDL_GetError());
    }
    set_window_icon(window);

#if defined(_WIN32)
    SDL_SysWMinfo wm_info;
    SDL_VERSION(&wm_info.version);
    if (!SDL_GetWindowWMInfo(window, &wm_info)) {
        exit_error("Failed to get window info: %s", SDL_GetError());
    }
    return ultramodern::renderer::WindowHandle{ wm_info.info.win.window, GetCurrentThreadId() };
#elif defined(__linux__) || defined(__ANDROID__)
    return ultramodern::renderer::WindowHandle{ window };
#else
    static_assert(false && "Only Linux and Windows are set up in this file so far.");
#endif
}

static void update_gfx(void*) {
    // Pumps the window's events (otherwise Windows marks it "Not Responding").
    recompinput::handle_events();

    // Mirrors RT64's Expand target (rt64_workload_queue.cpp): the window's
    // aspect ratio, never narrower than the game's 4:3.
    float widescreen_scale = 1.0f;
    if (ultramodern::renderer::get_graphics_config().ar_option == ultramodern::renderer::AspectRatio::Expand) {
        int width = 0, height = 0;
        SDL_GetWindowSize(window, &width, &height);
        if (width > 0 && height > 0) {
            widescreen_scale = std::max(1.0f, (float(width) / float(height)) / (4.0f / 3.0f));
        }
    }
    snp::set_widescreen_scale(widescreen_scale);
}

// --- Audio ----------------------------------------------------------------
// Push-based playback: queue whatever the game hands us, report how much is
// still queued. SDL converts from the game's sample rate to the device's.

static SDL_AudioDeviceID audio_device = 0;
static std::mutex audio_mutex;
static constexpr uint32_t audio_channels = 2;
static uint32_t game_frequency = 44100;

// The runtime's osAiGetLength (used by nothing in this game's audio thread,
// which gets snp_ai_length instead) is told exactly what's queued.
static constexpr uint32_t audio_headroom_vis = 0;

// Latency cap. Nothing drains a surplus on its own: when the game delivers a
// burst faster than real time (e.g. skipping a cutscene), the extra stays
// queued and every sound after it plays late by that much. Above the soft
// cap incoming chunks are dropped until it's back under (a small surplus
// drains without a gap); above the hard cap the queue is cleared at once.
static constexpr uint32_t audio_soft_cap_ms = 200;
static constexpr uint32_t audio_hard_cap_ms = 500;

static bool open_audio_device(uint32_t frequency) {
    std::lock_guard<std::mutex> lock(audio_mutex);

    if (audio_device != 0) {
        SDL_CloseAudioDevice(audio_device);
        audio_device = 0;
    }

    SDL_AudioSpec desired{};
    desired.freq = static_cast<int>(frequency);
    desired.format = AUDIO_F32SYS;
    desired.channels = static_cast<Uint8>(audio_channels);
    desired.samples = 512;

    // No allowed changes: SDL resamples to whatever the device runs at, so
    // queued audio is always in the game's own rate.
    audio_device = SDL_OpenAudioDevice(nullptr, 0, &desired, nullptr, 0);
    game_frequency = frequency;
    if (audio_device == 0) {
        fprintf(stderr, "Failed to open audio device: %s (continuing without sound)\n", SDL_GetError());
        return false;
    }

    SDL_PauseAudioDevice(audio_device, 0);
    return true;
}

// Hardware-like audio interface status for the game's audio thread
// (STATUS.md round 6). The game (libmus) sizes each audio frame from AI_LEN,
// which on hardware is what's left of the buffer playing now, and skips a
// frame while the AI's two-buffer queue is full. The runtime reports the
// whole queue as the length and never full, so the game's correction never
// started and it wrote 25% more audio than plays, which then piled up to the
// latency cap and was dropped: constant crackle. Hooks in snp.jp.toml
// replace both results in the audio thread (func_80052064) with these.
static std::deque<size_t> queued_chunks; // frames in each chunk not yet fully played, oldest first
static size_t queued_chunk_frames = 0;   // their total

// Drops chunks that have finished playing; audio_mutex must be held.
static size_t played_up_to_now() {
    size_t queued = audio_device != 0 ? SDL_GetQueuedAudioSize(audio_device) / (audio_channels * sizeof(float)) : 0;
    while (!queued_chunks.empty() && queued_chunk_frames - queued_chunks.front() >= queued) {
        queued_chunk_frames -= queued_chunks.front();
        queued_chunks.pop_front();
    }
    return queued;
}

// AI_LEN: bytes left in the chunk playing now.
extern "C" uint32_t snp_ai_length() {
    std::lock_guard<std::mutex> lock(audio_mutex);
    size_t queued = played_up_to_now();
    if (queued_chunks.empty()) {
        return 0;
    }
    size_t after_current = queued_chunk_frames - queued_chunks.front();
    size_t current = queued > after_current ? queued - after_current : 0;
    return (uint32_t)(current * 2 * sizeof(int16_t));
}

// AI_STATUS: FIFO full (bit 31) while two chunks wait behind the playing one,
// one more than the hardware, against host thread wakeup jitter.
extern "C" uint32_t snp_ai_status() {
    std::lock_guard<std::mutex> lock(audio_mutex);
    played_up_to_now();
    return queued_chunks.size() >= 3 ? 0x80000000u : 0;
}

static void queue_samples(int16_t* audio_data, size_t sample_count) {
    if (audio_device == 0) {
        return;
    }

    // Each stereo frame is one 32-bit word in RDRAM, which is stored
    // word-swapped, so the two 16-bit halves read back right-then-left.
    static std::vector<float> buffer;
    buffer.resize(sample_count);
    float scale = static_cast<float>(recompui::config::sound::get_main_volume() / 100.0) / 32768.0f;
    for (size_t i = 0; i + 1 < sample_count; i += 2) {
        buffer[i + 0] = audio_data[i + 1] * scale;
        buffer[i + 1] = audio_data[i + 0] * scale;
    }

    std::lock_guard<std::mutex> lock(audio_mutex);
    const size_t bytes_per_ms = game_frequency * audio_channels * sizeof(float) / 1000;
    const size_t queued_bytes = SDL_GetQueuedAudioSize(audio_device);

    if (queued_bytes > audio_hard_cap_ms * bytes_per_ms) {
        printf("[SNP AUDIO] %zu ms queued, resyncing\n", queued_bytes / bytes_per_ms);
        fflush(stdout);
        SDL_ClearQueuedAudio(audio_device);
        queued_chunks.clear();
        queued_chunk_frames = 0;
    }
    else if (queued_bytes > audio_soft_cap_ms * bytes_per_ms) {
        return;
    }
    SDL_QueueAudio(audio_device, buffer.data(), static_cast<Uint32>(sample_count * sizeof(float)));
    queued_chunks.push_back(sample_count / audio_channels);
    queued_chunk_frames += sample_count / audio_channels;
}

static size_t get_frames_remaining() {
    if (audio_device == 0) {
        return 0;
    }
    std::lock_guard<std::mutex> lock(audio_mutex);
    size_t queued_frames = SDL_GetQueuedAudioSize(audio_device) / (audio_channels * sizeof(float));
    size_t headroom_frames = game_frequency / 60 * audio_headroom_vis;
    return queued_frames > headroom_frames ? queued_frames - headroom_frames : 0;
}

static void set_frequency(uint32_t frequency) {
    if (frequency != game_frequency) {
        open_audio_device(frequency);
    }
}

// --- Input ------------------------------------------------------------

// Port 1 is always plugged in. Port 2 is while Second Player is on Game's
// 2-Player Mode and two controllers are connected, for the game's own 2-player
// mode (player 2 aims and shoots for player 1); see src/main/second_player.cpp.
// Saves are on the cartridge's EEPROM, so the only pak is the Rumble Pak.
static ultramodern::input::connected_device_info_t get_connected_device_info(int controller_num) {
    if (controller_num == 1 && snp::second_player::port2_plugged()) {
        return ultramodern::input::connected_device_info_t{
            .connected_device = ultramodern::input::Device::Controller,
            .connected_pak = ultramodern::input::Pak::None,
        };
    }
    if (controller_num != 0) {
        return ultramodern::input::connected_device_info_t{
            .connected_device = ultramodern::input::Device::None,
            .connected_pak = ultramodern::input::Pak::None,
        };
    }
    return ultramodern::input::connected_device_info_t{
        .connected_device = ultramodern::input::Device::Controller,
        .connected_pak = snp::config::get_rumble_pak() ? ultramodern::input::Pak::RumblePak : ultramodern::input::Pak::None,
    };
}

// The game's controller reads. Port 1 is player 1 (the keyboard, the mouse and
// every controller but player 2's); port 2, while plugged in, player 2's
// controller (empty until one joins); the others don't answer. The Roll inputs
// become double taps of a move button (src/main/roll_input.cpp). On Android
// player 1 also gets the on-screen touch controls, unless one of the game's
// menus has the input.
static bool get_n64_input(int player_index, uint16_t* buttons_out, float* x_out, float* y_out) {
    if (player_index == 0) {
        snp::second_player::update();
    }
    else if (player_index != 1 || !snp::second_player::port2_plugged()) {
        return false;
    }
    const bool got = recompinput::profiles::get_n64_input(player_index, buttons_out, x_out, y_out);
    snp::roll::apply(player_index, buttons_out);
#if defined(__ANDROID__)
    if ((player_index == 0) && !recompinput::game_input_disabled()) {
        snp::android::add_touch_input(buttons_out);
    }
#endif
    return got;
}

